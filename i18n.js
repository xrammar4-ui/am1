function setLanguage(lang, dir) {
  const t = translations[lang] || translations.en;
  document.documentElement.lang = lang;
  document.documentElement.dir = dir || (lang === "ar" || lang === "ur" ? "rtl" : "ltr");
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    if (t[key] !== undefined) {
      if (key === "logo") el.innerHTML = t[key].replace(".", "<span>.</span>");
      else el.textContent = t[key];
    }
  });
  const label = document.querySelector(`[data-lang="${lang}"]`)?.textContent || lang;
  document.getElementById("langLabel").textContent = label;
  document.querySelectorAll("#langMenu button").forEach(b => {
    b.classList.toggle("active", b.dataset.lang === lang);
  });
  localStorage.setItem("evex-lang", lang);
  localStorage.setItem("evex-dir", document.documentElement.dir);
}

window.setLanguage = setLanguage;
window.translations = translations;
